#!/usr/bin/env node
/**
 * Generates src/common-passwords.ts from a pinned SecLists list (MIT License).
 *
 * Usage: node scripts/generate-common-passwords.mjs
 */
import { writeFileSync } from 'node:fs'

const COMMIT = 'c205c36a445bff37f8e58a9ec829105cd4975c58'
const FILE = 'Passwords/Common-Credentials/xato-net-10-million-passwords-1000.txt'
const COUNT = 200
const LEET = { '@': 'a', '4': 'a', '0': 'o', '1': 'i', '3': 'e', '5': 's', '$': 's', '7': 't' }

const normalize = (word) => Array.from(word).map((char) => LEET[char] ?? char).join('')

const response = await fetch(`https://raw.githubusercontent.com/danielmiessler/SecLists/${COMMIT}/${FILE}`)
if (!response.ok) {
  throw new Error(`Could not download the list: ${response.status}`)
}

const seen = new Set()
const words = []
for (const line of (await response.text()).split(/\r?\n/)) {
  const word = line.trim().toLowerCase()
  const normalized = normalize(word)
  if (Array.from(word).length < 4 || seen.has(normalized)) {
    continue
  }
  seen.add(normalized)
  words.push(word)
  if (words.length === COUNT) {
    break
  }
}

const quote = (word) => `'${word.replace(/\\/g, '\\\\').replace(/'/g, '\\\'')}'`

writeFileSync(new URL('../src/common-passwords.ts', import.meta.url), `/**
 * The ${COUNT} most common passwords (4+ characters, distinct after normalization).
 *
 * Source: ${FILE.split('/').pop()} from SecLists (MIT License, Copyright (c) 2018 Daniel Miessler),
 * https://github.com/danielmiessler/SecLists/blob/${COMMIT}/${FILE}
 * Generated by scripts/generate-common-passwords.mjs; do not edit.
 */
export const commonPasswords: string[] = [
${words.map((word) => `  ${quote(word)},`).join('\n')}
]
`)

console.log('%d words written to src/common-passwords.ts', words.length)
